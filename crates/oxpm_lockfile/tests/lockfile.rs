use oxpm_lockfile::{Lockfile, Package, VERSION};
use oxpm_common::SourceType;

fn de<T: serde::de::DeserializeOwned>(toml_str: &str) -> T {
	toml::from_str(toml_str).expect("failed to deserialize")
}

#[test]
fn new_lockfile() {
	let lf = Lockfile::new();
	assert_eq!(lf.version, VERSION);
	assert!(lf.packages.is_empty());
}

#[test]
fn parse_empty_lockfile() {
	let lf = Lockfile::load_from_str("version = 1\n").expect("parse");
	assert_eq!(lf.version, 1);
	assert!(lf.packages.is_empty());
}

#[test]
fn parse_with_comment_header() {
	let input = r#"# This file is automatically @generated by oxpm.
# It is not intended for manual editing.

version = 1

[[package]]
name = "lodash"
version = "4.17.21"
source = "registry+https://registry.npmjs.org"
"#;
	let lf = Lockfile::load_from_str(input).expect("parse");
	assert_eq!(lf.version, 1);
	assert_eq!(lf.packages.len(), 1);
	assert_eq!(lf.packages[0].name.as_str(), "lodash");
}

#[test]
fn parse_multiple_packages() {
	let input = r#"
version = 1

[[package]]
name = "lodash"
version = "4.17.21"
source = "registry+https://registry.npmjs.org"
integrity = "sha512-abc"

[[package]]
name = "express"
version = "4.18.2"
source = "registry+https://registry.npmjs.org"
integrity = "sha512-def"
dependencies = ["accepts@1.3.8", "body-parser@1.20.1"]
devDependencies = ["jest@^29.0.0"]
"#;
	let lf = Lockfile::load_from_str(input).expect("parse");
	assert_eq!(lf.packages.len(), 2);
	assert_eq!(lf.packages[0].name.as_str(), "lodash");
	assert_eq!(lf.packages[1].name.as_str(), "express");
	let dev = lf.packages[1].dev_dependencies.as_ref().expect("dev");
	assert_eq!(dev.len(), 1);
	assert_eq!(dev[0].as_str(), "jest@^29.0.0");
	let deps = lf.packages[1].dependencies.as_ref().expect("deps");
	assert_eq!(deps.len(), 2);
}

