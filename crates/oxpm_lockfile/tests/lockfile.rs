#[test]
fn roundtrip() {
	let input = r#"
version = 1

[[package]]
name = "lodash"
version = "4.17.21"
source = "registry+https://registry.npmjs.org"
integrity = "sha512-abc"
dependencies = ["dep-a@1.0.0"]

[[package]]
name = "@types/node"
version = "20.11.0"
source = "registry+https://registry.npmjs.org"
integrity = "sha512-xyz"
devDependencies = ["jest@^29.0.0"]
"#;
	let lf = Lockfile::load_from_str(input).expect("parse");
	let serialized = lf.to_string_pretty().expect("serialize");
	let reparsed = Lockfile::load_from_str(&serialized).expect("reparse");
	assert_eq!(reparsed.version, lf.version);
	assert_eq!(reparsed.packages.len(), lf.packages.len());
	for (a, b) in reparsed.packages.iter().zip(lf.packages.iter()) {
		assert_eq!(a.name, b.name);
		assert_eq!(a.version.to_string(), b.version.to_string());
		assert_eq!(a.source, b.source);
		assert_eq!(a.integrity, b.integrity);
		assert_eq!(a.dev_dependencies, b.dev_dependencies);
	}
}

