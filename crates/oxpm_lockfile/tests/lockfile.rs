#[test]
fn save_and_load_file() {
	let dir = std::env::temp_dir().join("oxpm_lockfile_test");
	std::fs::create_dir_all(&dir).expect("mkdir");
	let path = dir.join("oxpm-lock.toml");

	let mut lf = Lockfile::new();
	lf.packages.push(Package {
		name: "test-pkg".into(),
		version: "1.2.3".parse().expect("version"),
		source: SourceType::parse("registry+https://registry.npmjs.org"),
		integrity: Some("sha512-test".into()),
		dependencies: None,
		dev_dependencies: None,
		optional_dependencies: None,
		peer_dependencies: None,
		bin: None,
		engines: None,
		os: None,
		cpu: None,
	});

	lf.save_to_path(&path).expect("save");
	let loaded = Lockfile::load_from_path(&path).expect("load");
	assert_eq!(loaded.packages.len(), 1);
	assert_eq!(loaded.packages[0].name.as_str(), "test-pkg");

	std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn package_with_all_fields() {
	let input = r#"
version = 1

[[package]]
name = "typescript"
version = "5.3.3"
source = "registry+https://registry.npmjs.org"
integrity = "sha512-full"
dependencies = ["dep@1.0.0"]
bin = true
devDependencies = ["jest@^29.0.0"]
optionalDependencies = ["fsevents@^2.0.0"]
peerDependencies = ["react@^18.0.0"]
engines = { node = ">=14.17" }
os = ["linux", "darwin"]
cpu = ["x64", "arm64"]
"#;
	let lf = Lockfile::load_from_str(input).expect("parse");
	let pkg = &lf.packages[0];
	assert_eq!(pkg.name.as_str(), "typescript");
	assert!(pkg.bin.is_some());
	let dev = pkg.dev_dependencies.as_ref().expect("dev");
	assert_eq!(dev.len(), 1);
	assert_eq!(dev[0].as_str(), "jest@^29.0.0");
	let peer = pkg.peer_dependencies.as_ref().expect("peer");
	assert_eq!(peer.len(), 1);
	assert_eq!(peer[0].as_str(), "react@^18.0.0");
	let engines = pkg.engines.as_ref().expect("engines");
	assert_eq!(engines.get("node").expect("node").as_str(), ">=14.17");
	let os = pkg.os.as_ref().expect("os");
	assert_eq!(os.len(), 2);
	let cpu = pkg.cpu.as_ref().expect("cpu");
	assert_eq!(cpu.len(), 2);
}

