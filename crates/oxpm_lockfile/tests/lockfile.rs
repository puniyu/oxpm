#[test]
fn dependencies_roundtrip() {
	let pkg: Package = de(r#"
name = "multi-deps"
version = "1.0.0"
source = "registry+https://registry.npmjs.org"
dependencies = ["a@1.0.0", "b@2.0.0", "@scope/pkg@3.0.0"]
devDependencies = ["dev@1.0.0"]
optionalDependencies = ["opt@1.0.0"]
peerDependencies = ["peer@1.0.0"]
"#);
	let serialized = toml::to_string(&pkg).expect("serialize");
	let reparsed: Package = de(&serialized);
	assert_eq!(pkg.dependencies, reparsed.dependencies);
	assert_eq!(pkg.dev_dependencies, reparsed.dev_dependencies);
	assert_eq!(pkg.optional_dependencies, reparsed.optional_dependencies);
	assert_eq!(pkg.peer_dependencies, reparsed.peer_dependencies);
}

